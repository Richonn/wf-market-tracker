#!/bin/bash
set -e
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
  CREATE USER wfmt_ro WITH PASSWORD '$WFMT_RO_PASSWORD';
  GRANT CONNECT ON DATABASE $POSTGRES_DB TO wfmt_ro;
  GRANT USAGE ON SCHEMA public TO wfmt_ro;
  GRANT SELECT ON ALL TABLES IN SCHEMA public TO wfmt_ro;
  ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT ON TABLES TO wfmt_ro;
EOSQL
